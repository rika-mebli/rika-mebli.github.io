function Get-Codes([string]$s) {
  $codes = New-Object System.Collections.Generic.List[string]
  foreach ($m in [regex]::Matches($s, '(?<![\p{L}\d])([MRDМРД])-?(\d+)(?:-(\d+))?(?![\p{L}\d])')) {
    $l = $m.Groups[1].Value
    if ($l -eq 'М') { $l = 'M' } elseif ($l -eq 'Р') { $l = 'R' } elseif ($l -eq 'Д') { $l = 'D' }
    $c = "$l-$($m.Groups[2].Value)"; if ($m.Groups[3].Success) { $c += "-$($m.Groups[3].Value)" }
    if (-not $codes.Contains($c)) { $codes.Add($c) }
  }
  return ,$codes
}
