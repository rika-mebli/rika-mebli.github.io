$PluralUa = @{ 'шафа' = 'шафи'; 'тумба' = 'тумби'; 'комод' = 'комоди'; 'стіл' = 'столи'; 'дзеркало' = 'дзеркала'; 'вішалка' = 'вішалки'; 'шафа-пенал' = 'шафи-пенали' }
$PluralRu = @{ 'шкаф' = 'шкафа'; 'тумба' = 'тумбы'; 'комод' = 'комода'; 'стол' = 'стола'; 'зеркало' = 'зеркала'; 'вешалка' = 'вешалки'; 'шкаф-пенал' = 'шкафа-пенала' }
# "Шафа розпашна VAYS R-9" -> "Шафа розпашна VAYS";  sets "... VAYS шафа R-26 шафа R-27 тумба R-28" -> "... VAYS: 2 шафи, тумба"
function Remove-ModelCodes([string]$core, [bool]$isList, [string]$lang) {
  $i = $core.IndexOf('VAYS')
  if ($i -lt 0) { $head = ''; $tail = $core } else { $head = $core.Substring(0, $i + 4); $tail = $core.Substring($i + 4) }
  $tail = [regex]::Replace($tail, '№\s*\d+', ' ')
  $tail = [regex]::Replace($tail, '(?<![\p{L}\d])[MRDМРД]-?\d+(?:-\d+)?(?![\p{L}\d])', ' ')
  $tail = (($tail -replace '\s*\+\s*', ' ') -replace '\s+', ' ').Trim()
  if ($isList -and $head) {
    $plural = $(if ($lang -eq 'ua') { $PluralUa } else { $PluralRu })
    $order = New-Object System.Collections.Generic.List[string]; $cnt = @{}
    foreach ($wd in @($tail -split ' ' | Where-Object { $_ })) { $k = $wd.ToLower(); if (-not $cnt.ContainsKey($k)) { $cnt[$k] = 0; $order.Add($k) }; $cnt[$k]++ }
    $parts = @(foreach ($k in $order) { if ($cnt[$k] -gt 1 -and $plural.ContainsKey($k)) { "$($cnt[$k]) $($plural[$k])" } elseif ($cnt[$k] -gt 1) { "$($cnt[$k]) x $k" } else { $k } })
    if ($parts.Count) { return "${head}: " + ($parts -join ', ') }
    return $head
  }
  return ((("$head $tail").Trim() -replace '\s+,', ',' -replace '\s+', ' ') -replace '[,\s]+$', '').Trim()
}
function Get-TypeEntry($it) {
  $t = $Types[$it.type]
  if (-not $t) { $tn = (Tr $ParamVal $it.type).ToLower(); $t = @{ ua = $tn; ru = "$($it.type)".ToLower(); roomUa = ''; roomRu = ''; useUa = 'облаштувати дім зручно й практично'; useRu = 'обустроить дом удобно и практично'; kwUa = @($tn); kwRu = @("$($it.type)".ToLower()) } }
  return $t
}
function Get-Title($it, [string]$lang, [bool]$keepCode) {
  $isUa = ($lang -eq 'ua'); $t = Get-TypeEntry $it
  $color = $(if ($isUa) { $it.color } else { ConvertTo-ColorRu $it.color })
  $plain = $(if ($isUa) { $it.coreUa } else { $it.coreRu })
  if (-not $keepCode) { $plain = Remove-ModelCodes $plain ([bool]($it.ncodes -gt 2 -or $it.num)) $lang }
  $tail = ''
  if ($it.tag) { $tail += ', ' + $(if ($isUa) { 'варіант' } else { 'вариант' }) + " $($it.tag)" }
  if ($it.dims) { $tail += ", $($it.dims) см" }
  $tail += $(if ($isUa) { ", колір $color" } else { ", цвет $color" })
  # the client removes the brand everywhere
  $noBrand = { param($s) if ($keepCode) { $s } else { $s -replace '\s+VAYS(?=[\s:,]|$)', '' } }
  $name = & $noBrand ($(if ($isUa) { Add-Room $plain $t.roomUa $roomPresentUa } else { Add-Room $plain $t.roomRu $roomPresentRu }) + $tail)
  if ($name.Length -gt 120) { $name = & $noBrand ($plain + $tail) }
  if ($name.Length -gt 120) { $name = $name -replace ', (колір|цвет) ', ', ' }
  return $name
}

