  $ms = [regex]::Matches($name, $re, $IC)
  if ($ms.Count -eq 0) { return @($name, '') }
  $m = $ms[$ms.Count - 1]
  return @($name.Remove($m.Index, $m.Length), $m.Groups[1].Value)
}
