# Synthetic takes no variants: every colour is its own card, so mix models and colours across the catalogue
if ($Format -eq 'synthetic') {
  $queues = New-Object System.Collections.Generic.List[object]; $qIndex = @{}
  foreach ($it in $ordered) {
    $qk = $(if ($it.groupId) { "g$($it.groupId)" } else { "i$($it.id)" })
    if (-not $qIndex.ContainsKey($qk)) { $qIndex[$qk] = New-Object System.Collections.Generic.List[object]; $queues.Add($qIndex[$qk]) }
    $qIndex[$qk].Add($it)
  }
  $rows = New-Object System.Collections.Generic.List[object]; $ri = 0; $maxLen = 0
  foreach ($q in $queues) {
    $inStock = @($q | Where-Object { $_.avail }); $noStock = @($q | Where-Object { -not $_.avail })
    $row = New-Object System.Collections.Generic.List[object]
    if ($inStock.Count) { $row.Add($inStock[0]) }
    if ($inStock.Count -gt 1) { $n2 = $inStock.Count - 1; for ($i2 = 0; $i2 -lt $n2; $i2++) { $row.Add($inStock[1 + (($i2 + $ri) % $n2)]) } }
    foreach ($x in $noStock) { $row.Add($x) }
    $rows.Add($row); $ri++; $maxLen = [math]::Max($maxLen, $row.Count)
  }
  $mixed = New-Object System.Collections.Generic.List[object]
  for ($r = 0; $r -lt $maxLen; $r++) { foreach ($row in $rows) { if ($r -lt $row.Count) { $mixed.Add($row[$r]) } } }
  $ordered = $mixed
}

