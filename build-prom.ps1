# without model codes a few different models get identical titles (e.g. desks M-15 and M-24) -> those keep the code
$clashModels = 0
if (-not $KeepModelCodes) {
  $clash = @{}
  foreach ($lang in 'ua', 'ru') {
    $titles = @{}
    foreach ($it in $items) {
      $tt = Get-Title $it $lang $false
      $gk = $(if ($it.groupId) { "g$($it.groupId)" } else { "i$($it.id)" })
      if (-not $titles.ContainsKey($tt)) { $titles[$tt] = New-Object 'System.Collections.Generic.HashSet[string]' }
      [void]$titles[$tt].Add($gk)
    }
    foreach ($tt in $titles.Keys) { if ($titles[$tt].Count -gt 1) { foreach ($gk in $titles[$tt]) { $clash[$gk] = $true } } }
  }
  # different models with one title get a neutral label ("варіант 1") instead of a brand / model code
  $clusters = @{}
  foreach ($it in $items) {
    $gk = $(if ($it.groupId) { "g$($it.groupId)" } else { "i$($it.id)" })
    if (-not $clash[$gk]) { continue }
    $cb = (Get-Title $it 'ua' $false) -replace ', колір .*$', ''
    if (-not $clusters.ContainsKey($cb)) { $clusters[$cb] = @{} }
    $clusters[$cb][$gk] = "$($it.model)"
  }
  $tagOf = @{}
  foreach ($cb in $clusters.Keys) {
    $pairs = [string[]]@($clusters[$cb].Keys | ForEach-Object { "$($clusters[$cb][$_])|$_" })
    [Array]::Sort($pairs, [StringComparer]::Ordinal)
    for ($pi2 = 0; $pi2 -lt $pairs.Count; $pi2++) { $tagOf[($pairs[$pi2] -split '\|')[1]] = $pi2 + 1 }
  }
  foreach ($it in $items) { $gk = $(if ($it.groupId) { "g$($it.groupId)" } else { "i$($it.id)" }); if ($tagOf.ContainsKey($gk)) { $it.tag = "$($tagOf[$gk])" } }
  $clashModels = $clash.Count
}

$byGroup = @{}
foreach ($it in $items) { if ($it.groupId) { if (-not $byGroup.ContainsKey($it.groupId)) { $byGroup[$it.groupId] = New-Object System.Collections.Generic.List[object] }; $byGroup[$it.groupId].Add($it) } }
$GroupColors = @{}
foreach ($gid in $byGroup.Keys) { $GroupColors[$gid] = @($byGroup[$gid] | ForEach-Object { $_.color }) }

# Prom shows the first offer of a group as the main one; the supplier lists colours alphabetically, so it was always
# "антрацит". Rotate the main colour between models (in stock, plain colour preferred) and put it first.
# The turn is kept per product type, so e.g. neighbouring chests of drawers are white, wenge, sonoma...
$palette = @('білий', 'венге темний', 'дуб сонома', 'бетон', 'дуб аппалачі', 'антрацит')
$ordered = New-Object System.Collections.Generic.List[object]; $placed = @{}; $typeTurn = @{}; $mainStats = @{}
foreach ($it in $items) {
  if (-not $it.groupId) { $ordered.Add($it); continue }
  if ($placed.ContainsKey($it.groupId)) { continue }
  $placed[$it.groupId] = $true
  $members = $byGroup[$it.groupId]; $main = $null; $gi = [int]$typeTurn["$($it.type)"]; $pick = -1
  for ($k = 0; $k -lt $palette.Count -and -not $main; $k++) {
    $base = $palette[($gi + $k) % $palette.Count]
    $cand = @($members | Where-Object { $_.avail -and (($_.color -split ' / ')[0] -eq $base) } | Sort-Object { $_.color.Contains('/') })
    if ($cand.Count) { $main = $cand[0]; $pick = ($gi + $k) % $palette.Count }
  }
  if (-not $main) { $main = @($members | Where-Object { $_.avail })[0] }
  if (-not $main) { $main = $members[0] }
  $typeTurn["$($it.type)"] = $(if ($pick -ge 0) { $pick + 1 } else { $gi + 1 })
  $mb = ($main.color -split ' / ')[0]; $mainStats[$mb] = 1 + [int]$mainStats[$mb]
  $ordered.Add($main)
  foreach ($m in $members) { if (-not [object]::ReferenceEquals($m, $main)) { $ordered.Add($m) } }
}

