  [void]$sb.Append('<p>' + (Encode (Format-Template $L.cta @{ t = $accText })) + '</p>')
  [void]$sb.Append('<p><strong>' + (Encode $L.delivery) + '</strong></p>')
  [void]$sb.Append('<p>' + (Encode $L.ship) + '</p><p>' + (Encode $L.pay) + '</p>')
  [void]$sb.Append('<p><strong>' + (Encode $L.trustHead) + '</strong></p><ul>')
  foreach ($x in $L.trust) { [void]$sb.Append('<li>' + (Encode $x) + '</li>') }
  [void]$sb.Append('</ul><p>' + (Encode $L.trustEnd) + '</p>')

  # ---- keywords
  $kw = New-Object System.Collections.Generic.List[string]
  $seen = New-Object 'System.Collections.Generic.HashSet[string]' ([StringComparer]::OrdinalIgnoreCase)
  $add = { param($s) $s = ($s -replace '\s+', ' ').Trim(); if ($s -and $seen.Add($s)) { $kw.Add($s) } }
  foreach ($s in $(if ($isUa) { $t.kwUa } else { $t.kwRu })) { & $add $s }
  $mainColor = ($color -split ' / ')[0]
  & $add "$type $mainColor"
  if ($it.W) { & $add "$type $($it.W) см" }
  & $add "$type $mat"
  & $add (Format-Template $L.buy @{ t = $accText })
  $kwStr = ''
  foreach ($s in $kw) { $next = $(if ($kwStr) { "$kwStr, $s" } else { $s }); if ($next.Length -gt 1024) { break }; $kwStr = $next }

  return @{ name = $name; desc = $sb.ToString(); kw = $kwStr }
}

